// Reproducible browser/Node extractions from manifest-verified Apache-2.0 sources.
// Excludes Electron app/file management and AI imports, retains editor logic.
import {readFile,writeFile,mkdir} from 'node:fs/promises'
const root = new URL('../',import.meta.url)
const read = path => readFile(new URL(`vendor/apps/sheets/src/${path}`,root),'utf8')
await mkdir(new URL('generated/',root),{recursive:true})
const banner = '// Generated by scripts/extract-upstream.mjs from fixed GenOffice sources; Apache-2.0.\n'
let api = await read('shared/desktop-api.ts')
api = api.slice(0,api.indexOf('export const aiSettingsInputSchema'))
// Keep complete workbook schemas and types; unrelated provider/UI type-only imports
// are referenced only in the excluded AI/application API section.
api = api.replace(/import type \{[\s\S]*?\} from '@genoffice\/ai-provider'\n/,'').replace(/import type \{ AiPanelPrefs \} from '@genoffice\/ui'\n/,'')
api = api.replace("'./ipc-channels'","'../vendor/apps/sheets/src/shared/ipc-channels'")
await writeFile(new URL('generated/desktop-api.ts',root),banner+api.replaceAll('@genoffice/xlsx-gateway/','../vendor/packages/xlsx-gateway/src/'))
let journal = await read('renderer/edit-journal.ts')
journal = journal.replaceAll("'../shared/desktop-api'","'./desktop-api'")
journal = journal.replace("import { INDENT_STEP_PX } from './selection-format'","const INDENT_STEP_PX = 8")
journal = journal.replace("import type { SharedFormulaResolver } from './shared-formula-journal'","type SharedFormulaResolver = (row: number, column: number, si: string) => string | null")
journal = journal.replace("import type { SheetProtectionInfo } from './sheet-protection'",`interface SheetProtectionInfo { protected: boolean; hasPassword: boolean; allow: import('../vendor/packages/xlsx-gateway/src/gateway/xlsx-protection').SheetProtectionAllow; password: import('../vendor/packages/xlsx-gateway/src/gateway/xlsx-protection-hash').SheetPasswordHash | null }`)
await writeFile(new URL('generated/edit-journal.ts',root),banner+journal.replaceAll('@genoffice/xlsx-gateway/','../vendor/packages/xlsx-gateway/src/'))
const main = await read('main/sheets-main.ts')
const start = main.indexOf('async function writeWorkbookTo(')
const end = main.indexOf('/** Copies the workbook into the temp snapshot dir;',start)
let save = main.slice(start,end).replace('async function writeWorkbookTo(','export async function writeWorkbookTo(').replace('client: XlsxSidecarClient','client: Sidecar')
// File persistence belongs to the host. Every gateway scratch file and the
// byte candidate stay inside the same private directory granted to the worker.
const saveCall = 'const mutation = await saveWorkbookViaSidecar({\n    client,'
if (!save.includes(saveCall)) throw Error('Upstream workbook save bridge changed')
save = save.replace(saveCall, saveCall + '\n    tempRoot: dirname(targetPath),\n    temporaryCandidate: true,')
await writeFile(new URL('generated/save-workbook.ts',root),banner+`import { dirname } from 'node:path'
import type { Sidecar } from '../sidecar'
import type { WorkbookSaveRequest } from './desktop-api'
import type { CellEdit, SheetStructuralOps } from '../vendor/packages/xlsx-gateway/src/gateway/xlsx-gateway'
import type { SheetEditPlan } from '../vendor/packages/xlsx-gateway/src/gateway/xlsx-sheets'
import { saveWorkbookViaSidecar } from '../vendor/packages/xlsx-gateway/src/gateway/xlsx-package-io'
interface SessionInfo { snapshotPath: string; sheetNames: Map<string,string> }
`+save)

const constants = await read('renderer/app-constants.ts')
await writeFile(new URL('generated/commands.ts',root),banner+constants.slice(constants.indexOf('export const SET_RANGE_VALUES_MUTATION'), constants.indexOf('/// Sheet-structure commands blocked')))
// Pull complete declarations (not hand-edited copies) from the upstream
// installer. The selected functions depend on workbook models, never Electron.
const ts = (await import('typescript')).default
const sync = await read('renderer/univer-sync.ts')
const names = new Set(['matrixBounds','toUniverStyle','toRichTextDocument','runHasFormatting','scaledFontSize','cellFontTextStyle','baselineOffsetOf','fontTextStyleOf','DV_ERROR_STYLES','toUniverDvRule','trimListItems','DvListSourceContext','resolveDvListSource','CfHighlightBuilder','buildConditionalRule','BuiltHighlightRule','patchBuiltHighlightRule','toCfValue','toCfFormula','CELLIS_FORMULA_CELL_LIMIT','cellIsBlankDiverges','buildCellIsFormula','buildHighlightCondition','buildTextCondition','synthesizeTextConditionFormula','buildCellIsNonNumeric','escapeCfWildcards','wrapOperand','applyDxfFormat','toUniverBorder','mapBorderStyle','mapHorizontalAlignment','mapVerticalAlignment','columnLetter'])
const ast = ts.createSourceFile('univer-sync.ts',sync,ts.ScriptTarget.Latest,true,ts.ScriptKind.TS)
const declarations = ast.statements.filter(stmt=>{
  const ids=ts.isVariableStatement(stmt)?stmt.declarationList.declarations.map(d=>d.name.getText(ast)):[stmt.name?.getText(ast)]
  return ids.some(id=>names.has(id))
}).map(stmt=>sync.slice(stmt.getFullStart(),stmt.end))
await writeFile(new URL('generated/file-rendering.ts',root),banner+`import { BooleanNumber, BaselineOffset, HorizontalAlign, VerticalAlign, BorderStyleTypes, WrapStrategy, type ICellData, type IStyleData, type IRange } from '@univerjs/core'
import type { FWorkbook } from '@univerjs/sheets/facade'
import { DataValidationRenderMode } from '@univerjs/core'
import { CFValueType, type IValueConfig } from '@univerjs/preset-sheets-conditional-formatting'
import { WORST_FIRST_ICON_SETS } from '../vendor/packages/xlsx-gateway/src/gateway/xlsx-cf'
import type { WorkbookCellStyle, WorkbookRangeResult, WorkbookFile, WorkbookRichRun } from './desktop-api'
import { escapeCssLeadingDigit, NO_FILL_STYLE, ooxmlTextRotationToUniver } from './edit-journal'
const INDENT_STEP_PX = 8
type UniverWorksheet = NonNullable<ReturnType<FWorkbook['getActiveSheet']>>
`+declarations.join('\n'))

const growth=(await read('renderer/grid-growth.ts')).replace("import type { UniverRuntime } from './univer-state'", "interface UniverRuntime { univer: import('@univerjs/core').Univer; univerAPI: import('@univerjs/core/facade').FUniver }")
await writeFile(new URL('generated/grid-growth.ts',root),banner+growth)
