import {act,render,screen,waitFor} from '@testing-library/react';
import {expect,it,vi} from 'vitest';
import {OfficeFileContent} from './OfficeFileContent';
import {officeFileApi} from '../../services/officeFileApi';
const pending=vi.hoisted(()=>({docx:undefined as undefined|(()=>void),xlsx:undefined as undefined|(()=>void),pptx:vi.fn()}));
vi.mock('./DocxEditor',async()=>{await new Promise<void>(resolve=>{pending.docx=resolve});return {DocxEditor:()=> <p>resolved Word component</p>}});
vi.mock('./XlsxEditor',async()=>{await new Promise<void>(resolve=>{pending.xlsx=resolve});return {XlsxEditor:()=> <p>resolved Excel component</p>}});
vi.mock('./PptxEditor',()=>{pending.pptx();return {PptxEditor:()=>null}});
vi.mock('../../services/officeFileApi',()=>({officeFileApi:{inspect:vi.fn(),save:vi.fn()}}));
vi.mock('../../../packages/office-docx/dist/full-editor.mjs',()=>({}));
vi.mock('../../../packages/office-xlsx/dist/browser.mjs',()=>({}));
const binding={workspaceId:'w',generation:'g'},baseline={object:{workspaceId:'w',scope:{kind:'project' as const,projectId:7},kind:'file' as const,id:'1'},versionNumber:1,expectedContentHash:'hash1'};
const props={binding,baseline,toolbar:null,readOnly:true,registerFlush:()=>()=>{},onDirtyChange:vi.fn(),onSaved:vi.fn()};
it('imports only the selected component while native inspect is pending, retaining loading and the File menu',async()=>{
 let finish!: (value:unknown)=>void;
 vi.mocked(officeFileApi.inspect).mockImplementationOnce(()=>new Promise(resolve=>{finish=resolve}) as never);
 const menu=document.createElement('span');document.body.append(menu);
 const view=render(<OfficeFileContent {...props} menuToolbar={menu} fileName="sample.docx"/>);
 await waitFor(()=>expect(pending.docx).toBeTypeOf('function'));
 expect(officeFileApi.inspect).toHaveBeenCalledWith(binding,baseline);
 expect(pending.xlsx).toBeUndefined();expect(pending.pptx).not.toHaveBeenCalled();
 expect(screen.queryByText('resolved Word component')).toBeNull();
 expect(view.container.querySelector('[role="status"]')).not.toBeNull();
 await act(async()=>finish({model:{format:'docx',nodes:[]}}));
 expect(screen.getByRole('button',{name:'文件菜单'})).toBeVisible();
 expect(screen.queryByText('resolved Word component')).toBeNull();
 await act(async()=>{pending.docx!();await vi.dynamicImportSettled()});
 expect(await screen.findByText('resolved Word component')).toBeVisible();
 view.unmount();menu.remove();
});
it('closing while the selected component import is pending cannot mount it after resolution',async()=>{
 vi.mocked(officeFileApi.inspect).mockResolvedValueOnce({model:{format:'xlsx',sheets:[]}} as never);
 const view=render(<OfficeFileContent {...props} fileName="sample.xlsx"/>);
 await waitFor(()=>expect(pending.xlsx).toBeTypeOf('function'));
 view.unmount();
 await act(async()=>{pending.xlsx!();await vi.dynamicImportSettled()});
 expect(screen.queryByText('resolved Excel component')).toBeNull();
 expect(officeFileApi.save).not.toHaveBeenCalled();
});
